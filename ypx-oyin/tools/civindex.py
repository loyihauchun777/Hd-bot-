# Collect models/civ_*.json into js/civdata.js
import json, glob, os
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'web3d') + os.sep
models = [json.load(open(p)) for p in sorted(glob.glob(OUT + 'models/civ_*.json'))]
open(OUT + 'js/civdata.js', 'w').write('// Generated by civindex.py from models/civ_*.json (street cars from reference sheets).\nexport const CIV_MODELS = ' + json.dumps(models) + ';\n')
print([m['id'] for m in models])
